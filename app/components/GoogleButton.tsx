"use client";

import { useState } from "react";
import { createClient } from "@/lib/supabase/client";

// White button with a thin border, like the FitCheck sign in. Reads well on
// cream, on white and on top of a dark photo.
export default function GoogleButton() {
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");

  async function signIn() {
    setBusy(true);
    setError("");
    const supabase = createClient();
    const { error } = await supabase.auth.signInWithOAuth({
      provider: "google",
      options: { redirectTo: `${window.location.origin}/auth/callback` },
    });
    if (error) {
      console.error("Sign in failed:", error);
      setError("We could not start sign in. Please try again.");
      setBusy(false);
    }
    // On success the browser leaves for Google, so busy stays on.
  }

  return (
    <div className="flex flex-col gap-3">
      <button onClick={signIn} disabled={busy} className="btn btn-outline">
        <svg width="18" height="18" viewBox="0 0 48 48" aria-hidden="true">
          <path fill="#EA4335" d="M24 9.5c3.5 0 6.6 1.2 9.1 3.6l6.8-6.8C35.8 2.4 30.3 0 24 0 14.6 0 6.6 5.4 2.6 13.2l7.9 6.2C12.4 13.7 17.7 9.5 24 9.5z" />
          <path fill="#4285F4" d="M46.1 24.5c0-1.6-.1-3.1-.4-4.5H24v9h12.4c-.5 2.9-2.2 5.3-4.6 6.9l7.4 5.8c4.3-4 6.9-9.9 6.9-17.2z" />
          <path fill="#FBBC05" d="M10.5 28.6A14.5 14.5 0 0 1 9.5 24c0-1.6.3-3.2.8-4.6l-7.9-6.2A24 24 0 0 0 0 24c0 3.9.9 7.5 2.6 10.8l7.9-6.2z" />
          <path fill="#34A853" d="M24 48c6.5 0 11.9-2.1 15.9-5.8l-7.4-5.8c-2.1 1.4-4.8 2.2-8.5 2.2-6.3 0-11.6-4.2-13.5-9.9l-7.9 6.2C6.6 42.6 14.6 48 24 48z" />
        </svg>
        {busy ? "Opening Google..." : "Continue with Google"}
      </button>
      {error && (
        <p role="alert" className="text-center text-sm text-[#C0392B]">
          {error}
        </p>
      )}
    </div>
  );
}
